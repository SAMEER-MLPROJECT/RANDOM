"""Rebuild shipped point-in-time graph partitions and the frozen isolation forest.

Run from any directory. Dependencies and methodology are in docs/GRAPH_METHODS.md.
"""
import json
from pathlib import Path
import subprocess

import networkx as nx
import numpy as np
from sklearn.ensemble import IsolationForest
from sklearn.metrics import adjusted_rand_score

ROOT = Path(__file__).resolve().parents[1]
FIRST, END = 90, 545
TRAIN_END = 179
THRESHOLD = 0.52


def market_prices():
    source = """
    import {tape} from './dist/market.js';
    console.log(JSON.stringify(tape.window(%d,%d).map(row=>row.prices)))
    """ % (END, END + 1)
    result = subprocess.check_output(["node", "--input-type=module", "-e", source], cwd=ROOT)
    return np.asarray(json.loads(result))


def features(r, day):
    # r[t-1] is the return ending at t. Both windows end on or before day.
    now = np.corrcoef(r[day-45:day].T)
    prior = np.corrcoef(r[day-90:day-45].T)
    n = len(now)
    pairs = np.triu_indices(n, 1)
    a, b = now[pairs], prior[pairs]
    fisher = lambda x: np.arctanh(np.clip(x, -.999999, .999999))
    z = (fisher(a) - fisher(b)) / np.sqrt(2 / 42)
    return now, np.column_stack((a, b, a-b, z))


def partition(corr):
    graph = nx.Graph()
    graph.add_nodes_from(range(len(corr)))
    for i in graph:
        for j in range(i+1, len(corr)):
            if corr[i, j] >= THRESHOLD:
                graph.add_edge(i, j, weight=float(corr[i, j]))
    groups = nx.community.louvain_communities(graph, weight="weight", seed=21)
    lookup = {node: min(group) for group in groups for node in group}
    return [lookup[i] for i in range(len(corr))]


def main():
    prices = market_prices()
    r = prices[1:] / prices[:-1] - 1
    # Fixed stride reduces near-duplicate windows. Pairs within each day still depend.
    trained = np.vstack([features(r, day)[1] for day in range(94, TRAIN_END+1, 5)])
    forest = IsolationForest(n_estimators=32, max_samples=96, contamination=.05,
                             random_state=92031, n_jobs=1).fit(trained)
    trees = []
    for estimator in forest.estimators_:
        t = estimator.tree_
        trees.append([[int(left), int(right), int(feature), round(float(split), 12), int(n)]
                      for left, right, feature, split, n in
                      zip(t.children_left, t.children_right, t.feature, t.threshold, t.n_node_samples)])
    groups = [partition(features(r, day)[0]) for day in range(FIRST, END+1)]
    first_live = 180
    refs = -forest.score_samples(features(r, first_live)[1])
    data = dict(first=FIRST, last=END, groups=groups, trainEnd=TRAIN_END,
                samples=forest.max_samples_, cutoff=-forest.offset_, trees=trees,
                trainRows=len(trained), refScores=refs.round(10).tolist())
    payload = json.dumps(data, separators=(",", ":"), allow_nan=False)
    (ROOT / "dist" / "graph-data.js").write_text("// Generated by research/graph-models.py\nexport default " + payload + ";\n")
    print(f"{len(groups)} as-of partitions, {len(trained)} training pair windows, {len(trees)} trees.")
    print("Initial adjusted Rand:", adjusted_rand_score(groups[180-FIRST],groups[135-FIRST]))
    print("Initial flags:", int(np.sum(refs > data["cutoff"])))


if __name__ == "__main__":
    main()
